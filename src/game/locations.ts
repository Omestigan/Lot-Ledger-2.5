export type Continent =
  | 'North America'
  | 'South America'
  | 'Europe'
  | 'Asia'
  | 'Africa'
  | 'Middle East'
  | 'Oceania';

export interface WorldLocation {
  id: string;
  city: string;
  country: string;
  continent: Continent;
  countryCode: string;
  flag: string;
  lat: number;
  lng: number;
  currency: string;
  currencySymbol: string;
  currencyMultiplier?: number; // Price ratio vs CAD/USD (e.g. 1.0 for CAD/USD, 110 for JPY, 0.72 for GBP, 0.85 for EUR, 2.7 for AED)
  taxRate: number; // e.g. 0.13 for 13%
  taxName: string; // e.g. "HST", "VAT", "Sales Tax"
  climate: 'arctic' | 'temperate_salt' | 'temperate_mild' | 'desert_arid' | 'tropical_humid' | 'mediterranean';
  climateLabel: string;
  rustRisk: number; // multiplier e.g. 0.1 for desert, 1.8 for salt belt
  sunDamageRisk: number; // multiplier e.g. 0.2 for arctic, 1.8 for desert
  preferredClasses: ('compact' | 'sedan' | 'suv' | 'truck' | 'van' | 'sport' | 'lux' | 'hatch' | 'conv')[];
  inspectionName: string; // e.g. "TÜV Rheinland", "MOT Inspection", "Safety Standards Certificate"
  baseRegCost: number;
  inspectionCost: number;
  description: string;
  experienceHighlight: string;
  mapsUrl?: string; // Direct verified link to Google Maps (maps.google.com)
  wikipediaUrl?: string; // Direct verified link to Wikipedia.com
  mapsSource?: string; // e.g. "maps.google.com & wikipedia.org"
  responseTimeMs?: number; // Measured telemetry discovery latency in ms
}

export function getGoogleMapsUrl(loc: WorldLocation): string {
  if (loc.mapsUrl) return loc.mapsUrl;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${loc.city}, ${loc.country}`)}`;
}

export function getWikipediaUrl(loc: WorldLocation): string {
  if (loc.wikipediaUrl) return loc.wikipediaUrl;
  return `https://en.wikipedia.org/wiki/${encodeURIComponent(loc.city)}`;
}


const CUSTOM_CITIES_KEY = 'lot_ledger_custom_world_cities_v1';

export function getCustomDiscoveredCities(): WorldLocation[] {
  try {
    const raw = localStorage.getItem(CUSTOM_CITIES_KEY);
    if (raw) return JSON.parse(raw);
  } catch (e) {
    console.warn('Failed to parse custom cities:', e);
  }
  return [];
}

export function saveCustomDiscoveredCity(city: WorldLocation) {
  try {
    const existing = getCustomDiscoveredCities().filter((c) => c.id !== city.id && c.city.toLowerCase() !== city.city.toLowerCase());
    existing.unshift(city);
    localStorage.setItem(CUSTOM_CITIES_KEY, JSON.stringify(existing.slice(0, 50)));
  } catch (e) {
    console.warn('Failed to save custom city:', e);
  }
}

